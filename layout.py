def ground_equivalent(node):
    """J205 -> J005, B318 -> B018, S107 -> S007 (same spot on every floor)."""
    return node[0] + "0" + node[2:]


def position(node):
    return COORDS[ground_equivalent(node)]


# 3x3 matrices that map the shared coordinates above onto each floor's photo
# (pixels of the 1600 x 1200 photos in floorplans/). Fitted from ~40 room labels
# per photo, average error about 4 px.
HOMOGRAPHY = {
    0: [[1.260835303388495, 0, 0], [0, 1.260835303388495, 0], [0, 0, 1]],
    1: [[0.4585464, -0.01830277, 85.06323947], [-0.07504424, 0.50685115, 150.85252284], [-8.764e-05, -2.286e-05, 0.63883822]],
    2: [[0.53703066, -0.03397049, 90.12712435], [-0.02585733, 0.5289752, 94.03931519], [-3.411e-05, -3.506e-05, 0.6148308]],
    3: [[0.50190327, -0.02447686, 115.73856999], [-0.01638089, 0.47349001, 131.37308752], [-5.34e-06, -4.162e-05, 0.60106263]],
}


def photo_position(node, floor):
    """Pixel position of a node on that floor's photo."""
    x, y = position(node)
    m = HOMOGRAPHY[floor]
    w = m[2][0] * x + m[2][1] * y + m[2][2]
    return ((m[0][0] * x + m[0][1] * y + m[0][2]) / w,
            (m[1][0] * x + m[1][1] * y + m[1][2]) / w)